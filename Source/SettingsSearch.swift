    static func normalized(_ text: String) -> String {
        text.lowercased()
            .replacingOccurrences(of: "ё", with: "е")
            .folding(options: [.diacriticInsensitive], locale: Locale(identifier: "ru_RU"))
    }

    // Every word of the query must occur somewhere; titles rank first.
    static func search(_ query: String, limit: Int = 30) -> [SettingsSearchEntry] {
        let words = normalized(query).split(whereSeparator: { $0 == " " || $0 == "," }).map(String.init)
        guard !words.isEmpty else { return [] }
        var scored: [(Int, Int, SettingsSearchEntry)] = []
        for (position, entry) in index.enumerated() {
            let title = normalized(entry.title)
            let all = title + " " + normalized(entry.sectionTitle) + " " + normalized(entry.keywords)
            guard words.allSatisfy({ all.contains($0) }) else { continue }
            var score = 0
            for word in words {
                if title.hasPrefix(word) { score += 30 }
                else if title.split(separator: " ").contains(where: { $0.hasPrefix(word) }) { score += 20 }
                else if title.contains(word) { score += 12 }
                else if normalized(entry.sectionTitle).contains(word) { score += 6 }
                else { score += 3 }
            }
            scored.append((score, position, entry))
        }
        return scored.sorted { $0.0 != $1.0 ? $0.0 > $1.0 : $0.1 < $1.1 }
            .prefix(limit).map(\.2)
    }
